#pragma once
// ============================================================================
// optimizer.h — агрессивные системные твики через чистый WinAPI.
//
// Всё, что делает этот модуль, обратимо. Перед каждым изменением реестра
// нужно снять слепок (backup::collectSnapshot), а в конце — сохранить его в
// файл (backup::saveSnapshotToFile). Функции имеют вид bool XXX() и в случае
// неудачи возвращают false, не меняя состояние нижележащих механизмов.
// ============================================================================

#include <windows.h>

#include <string>
#include <vector>

namespace opt {

// Сообщение о последней ошибке последнего вызванного твика (для GUI).
std::wstring lastErrorText();

// ---------------------------------------------------------------------------
// 1. Очистка Standby (кэша) памяти через NtSetSystemInformation.
//    Без прав администратора не сработает — вызывающая сторона должна
//    запросить UAC-повышение.
// ---------------------------------------------------------------------------
bool clearStandbyMemory();

// ---------------------------------------------------------------------------
// 2. Работа с процессом игры.
//    gamePid — PID игрового процесса (0 = текущий процесс приложения).
//    Устанавливает приоритет HIGH_PRIORITY_CLASS и, опционально, запрещает
//    размещение потоков на «фоновых» ядрах (последней половины, где чаще
//    всего крутятся службы и планировщик).
//    Возвращает handle процесса (необходимо CloseHandle у стороны-владельца).
// ---------------------------------------------------------------------------
bool setGamePriority(DWORD gamePid);
bool setGameAffinity(DWORD gamePid, bool disableBackgroundCores);
DWORD currentGamePid();

// ---------------------------------------------------------------------------
// 3. Твики реестра: Game Bar, DVR, ускорение мыши.
// ---------------------------------------------------------------------------
bool disableGameBar();      // отключает Auto Game Mode
bool disableGameDvr();      // отключает запись фоновых клипов
bool disableMouseAccel();   // убирает «ускорение» мыши (скорость -> усиление)
bool enableMouseAccel();    // возвращает ускорение (для Restore) — используй свой слепок

// ---------------------------------------------------------------------------
// 4. Nagle-алгоритм для сетевых игр (по всем сетевым интерфейсам).
// ---------------------------------------------------------------------------
bool disableNagle();        // TcpAckFrequency=1, TCPNoDelay=1, TcpDelAckTicks=0
bool enableNagle();         // возвращает значения (2, 0, 1) для отката

// ---------------------------------------------------------------------------
// 5. Службы, съедающие ресурсы: WSearch, SysMain (Superfetch), DiagTrack,
//    MapsBroker (Служба карт Windows). startService=1 останавливает и
//    запрещает автозапуск; startService=0 разрешает обратно.
// ---------------------------------------------------------------------------
struct ServiceJob {
    const wchar_t* name; // внутреннее имя службы
    const wchar_t* display;
};
const std::vector<ServiceJob>& targetServices();

bool disableBackgroundServices();  // остановить + Start=4 (Запрещено)
bool restoreBackgroundServices();  // Start=2 (Авто) + запустить

// ---------------------------------------------------------------------------
// 6. Таймер высокого разрешения.
//    timeBeginPeriod(1) — нить подаёт заявку на 1 мс. disabledynamictick
//    отключает динамический тик ядра (на Windows 11 часто улучшает
//    стабильность frametime). Требует прав администратора.
// ---------------------------------------------------------------------------
bool setHighResolutionTimer();  // timeBeginPeriod(1) процессный + bcdedit
bool restoreTimerSettings();    // timeEndPeriod + bcdedit resetdisabledynamictick

} // namespace opt